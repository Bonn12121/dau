import type { Question, Quiz } from "@/game/types";

/* Helper builder for multiple-choice questions */
function mc(
  id: string,
  kicker: string,
  prompt: string,
  opts: string[],
  answer: "A" | "B" | "C" | "D",
  passage?: string,
  explanation?: string,
): Question {
  const idx = "ABCD".indexOf(answer);
  return {
    id,
    type: "mc",
    kicker,
    prompt,
    passage,
    timeLimit: 25,
    points: 1000,
    examWeight: 0.25,
    choices: opts.map((text, i) => ({ id: `${id}-${"abcd"[i]}`, text })),
    correctIds: [`${id}-${"abcd"[idx]}`],
    explanation,
  };
}

