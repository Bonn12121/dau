import type { Question, Quiz } from "@/game/types";

const P = 1000;

function mc(
  id: string,
  kicker: string,
  prompt: string,
  options: string[],
  correct: number,
  explanation: string,
  hint = "",
): Question {
  return {
    id,
    type: "mc",
    kicker,
    prompt,
    explanation,
    hint,
    timeLimit: 35,
    points: P,
    examWeight: 0.25,
    keepOrder: true,
    choices: options.map((text, i) => ({ id: "abcd"[i] ?? `o${i}`, text })),
    correctIds: ["abcd"[correct] ?? "a"],
  };
}

function tf(
  id: string,
  kicker: string,
  passage: string,
  prompt: string,
  answer: boolean,
  explanation: string,
): Question {
  return {
    id,
    type: "tf",
    kicker,
    passage,
    prompt,
    tf: answer,
    explanation,
    hint: "Đối chiếu với bài học và chuẩn mực đạo đức.",
    timeLimit: 30,
    points: P,
    examWeight: 0.25,
    keepOrder: true,
  };
}

